const GENERIC: Record<string, LucideIcon> = {
  sql: Database,
  powershell: FileTerminal,
  bat: FileTerminal,
  ini: FileCog,
  log: ScrollText,
};

export function SyntaxIcon({ id, size = 16 }: { id: string; size?: number }) {
  const brand = BRAND[id];
  if (brand) return <BrandIcon icon={brand} size={size} className="syntax-icon" />;
  const Icon = GENERIC[id] ?? FileCode;
  return <Icon size={size} strokeWidth={1.75} className="syntax-icon" />;
}
