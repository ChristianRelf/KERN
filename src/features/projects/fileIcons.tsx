function render(g: Glyph, size: number) {
  if ("path" in g) return <BrandIcon icon={g} size={size - 2} className="file-icon file-icon--brand" />;
  const Icon = g;
  return <Icon size={size} strokeWidth={1.75} className="file-icon" />;
}

export function FileTypeIcon({ entry, size = 15 }: { entry: Pick<FileEntry, "name" | "isDir" | "isLink" | "program" | "sensitive">; size?: number }) {
  const lower = entry.name.toLowerCase();
  if (entry.isDir) {
    const Icon = entry.isLink ? FolderSymlink : (FOLDERS[lower] ?? Folder);
    return <Icon size={size} strokeWidth={1.75} className="file-icon file-icon--dir" />;
  }
  if (entry.sensitive && !/^\.env/.test(lower)) return <FileLock size={size} strokeWidth={1.75} className="file-icon" />;
  const ext = lower.includes(".") ? lower.slice(lower.lastIndexOf(".") + 1) : "";
  const known = BY_NAME[lower] ?? BY_PATTERN.find(([re]) => re.test(lower))?.[1] ?? BY_EXT[ext];
  if (known) return render(known, size);
  if (entry.program) return <FileTerminal size={size} strokeWidth={1.75} className="file-icon" />;
  return render(GENERIC.find(([re]) => re.test(ext))?.[1] ?? File, size);
}
